create policy "profiles_read_own" on public.profiles for select
to authenticated using (id = (select auth.uid()) or public.is_admin());
create policy "profiles_update_own" on public.profiles for update
to authenticated using (id = (select auth.uid()))
with check (id = (select auth.uid()));

-- Un cliente puede modificar su nombre/teléfono, nunca asignarse otro rol.
revoke update on public.profiles from authenticated;
grant update (full_name, phone) on public.profiles to authenticated;

create policy "vehicles_read_active_or_own" on public.vehicles for select
to authenticated using (active or driver_id = (select auth.uid()) or public.is_admin());
create policy "vehicles_admin_all" on public.vehicles for all
to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "moves_read_participant" on public.move_requests for select
to authenticated using (
  customer_id = (select auth.uid())
  or driver_id = (select auth.uid())
  or public.is_admin()
);
create policy "moves_customer_create" on public.move_requests for insert
to authenticated with check (
  customer_id = (select auth.uid())
  and driver_id is null
  and vehicle_id is null
  and status in ('draft', 'requested')
);
create policy "moves_admin_all" on public.move_requests for all
to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "history_read_participant" on public.move_status_history for select
to authenticated using (public.can_access_move(move_id));
create policy "history_admin_all" on public.move_status_history for all
to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "driver_locations_read_participant" on public.driver_locations for select
to authenticated using (public.can_access_move(move_id));
create policy "tracking_points_read_participant" on public.tracking_points for select
to authenticated using (public.can_access_move(move_id));

revoke insert, update, delete on public.driver_locations from authenticated;
revoke insert, update, delete on public.tracking_points from authenticated;
revoke execute on function public.record_driver_location(
  uuid, double precision, double precision, double precision,
  double precision, double precision, timestamptz
) from public, anon;
grant execute on function public.record_driver_location(
  uuid, double precision, double precision, double precision,
  double precision, double precision, timestamptz
) to authenticated;

-- Los canales move:<uuid> son privados. Realtime evalúa estas políticas al
-- suscribirse y al publicar; solo cliente, conductor asignado o admin acceden.
create policy "move_broadcast_read" on realtime.messages for select
to authenticated using (
  realtime.messages.extension = 'broadcast'
  and public.can_access_move_topic((select realtime.topic()))
);
create policy "move_broadcast_send" on realtime.messages for insert
to authenticated with check (
  realtime.messages.extension = 'broadcast'
  and public.can_access_move_topic((select realtime.topic()))
);

create or replace function public.log_initial_move_status()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.move_status_history (move_id, status, changed_by)
  values (new.id, new.status, (select auth.uid()));
  return new;
end;
$$;

create trigger move_initial_status
after insert on public.move_requests
for each row execute function public.log_initial_move_status();

create or replace function public.log_changed_move_status()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.status is distinct from old.status then
    insert into public.move_status_history (move_id, status, changed_by)
    values (new.id, new.status, (select auth.uid()));
  end if;
  return new;
end;
$$;

create trigger move_changed_status
after update of status on public.move_requests
for each row execute function public.log_changed_move_status();
