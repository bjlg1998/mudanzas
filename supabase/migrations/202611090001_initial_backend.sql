-- Backend inicial de Mudanzas: usuarios, solicitudes, vehículos y seguimiento.
create extension if not exists postgis with schema extensions;

create type public.app_role as enum ('customer', 'driver', 'admin');
create type public.move_status as enum (
  'draft',
  'requested',
  'quoted',
  'accepted',
  'driver_assigned',
  'in_progress',
  'completed',
  'cancelled'
);
create type public.vehicle_type as enum (
  'motocarro',
  'camioneta_estacas',
  'turbo'
);

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role public.app_role not null default 'customer',
  full_name text,
  phone text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.vehicles (
  id uuid primary key default gen_random_uuid(),
  driver_id uuid not null references public.profiles(id) on delete cascade,
  type public.vehicle_type not null,
  plate text not null unique,
  capacity_kg integer check (capacity_kg is null or capacity_kg > 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.move_requests (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.profiles(id),
  driver_id uuid references public.profiles(id),
  vehicle_id uuid references public.vehicles(id),
  vehicle_type public.vehicle_type not null,
  origin_address text not null check (length(trim(origin_address)) > 0),
  origin_latitude double precision not null check (origin_latitude between -90 and 90),
  origin_longitude double precision not null check (origin_longitude between -180 and 180),
  origin_point extensions.geography(point, 4326)
    generated always as (
      extensions.st_setsrid(
        extensions.st_makepoint(origin_longitude, origin_latitude),
        4326
      )::extensions.geography
    ) stored,
  destination_address text not null check (length(trim(destination_address)) > 0),
  destination_latitude double precision not null check (destination_latitude between -90 and 90),
  destination_longitude double precision not null check (destination_longitude between -180 and 180),
  destination_point extensions.geography(point, 4326)
    generated always as (
      extensions.st_setsrid(
        extensions.st_makepoint(destination_longitude, destination_latitude),
        4326
      )::extensions.geography
    ) stored,
  route_geojson jsonb,
  route_distance_meters integer check (route_distance_meters is null or route_distance_meters >= 0),
  route_duration_seconds integer check (route_duration_seconds is null or route_duration_seconds >= 0),
  status public.move_status not null default 'requested',
  requested_at timestamptz not null default now(),
  started_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint assigned_vehicle_requires_driver
    check (vehicle_id is null or driver_id is not null)
);

create index move_requests_customer_idx on public.move_requests(customer_id, created_at desc);
create index move_requests_driver_idx on public.move_requests(driver_id, created_at desc);
create index move_requests_origin_gix on public.move_requests using gist(origin_point);
create index move_requests_destination_gix on public.move_requests using gist(destination_point);

create table public.move_status_history (
  id bigint generated by default as identity primary key,
  move_id uuid not null references public.move_requests(id) on delete cascade,
  status public.move_status not null,
  changed_by uuid references public.profiles(id),
  note text,
  created_at timestamptz not null default now()
);

create index move_status_history_move_idx
  on public.move_status_history(move_id, created_at desc);

create table public.driver_locations (
  move_id uuid primary key references public.move_requests(id) on delete cascade,
  driver_id uuid not null references public.profiles(id),
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  point extensions.geography(point, 4326)
    generated always as (
      extensions.st_setsrid(
        extensions.st_makepoint(longitude, latitude),
        4326
      )::extensions.geography
    ) stored,
  heading double precision,
  speed double precision,
  accuracy double precision,
  captured_at timestamptz not null,
  updated_at timestamptz not null default now()
);

create index driver_locations_point_gix on public.driver_locations using gist(point);

create table public.tracking_points (
  id bigint generated by default as identity primary key,
  move_id uuid not null references public.move_requests(id) on delete cascade,
  driver_id uuid not null references public.profiles(id),
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  point extensions.geography(point, 4326)
    generated always as (
      extensions.st_setsrid(
        extensions.st_makepoint(longitude, latitude),
        4326
      )::extensions.geography
    ) stored,
  heading double precision,
  speed double precision,
  accuracy double precision,
  captured_at timestamptz not null
);

create index tracking_points_move_idx
  on public.tracking_points(move_id, captured_at desc);
create index tracking_points_point_gix on public.tracking_points using gist(point);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_updated_at before update on public.profiles
for each row execute function public.set_updated_at();
create trigger vehicles_updated_at before update on public.vehicles
for each row execute function public.set_updated_at();
create trigger move_requests_updated_at before update on public.move_requests
for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''));
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

create or replace function public.can_access_move(p_move_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.move_requests
    where id = p_move_id
      and (
        customer_id = (select auth.uid())
        or driver_id = (select auth.uid())
        or public.is_admin()
      )
  );
$$;

create or replace function public.can_access_move_topic(p_topic text)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  move_text text;
begin
  if p_topic !~ '^move:[0-9a-fA-F-]{36}$' then
    return false;
  end if;
  move_text := split_part(p_topic, ':', 2);
  return public.can_access_move(move_text::uuid);
exception when invalid_text_representation then
  return false;
end;
$$;

create or replace function public.record_driver_location(
  p_move_id uuid,
  p_latitude double precision,
  p_longitude double precision,
  p_heading double precision default null,
  p_speed double precision default null,
  p_accuracy double precision default null,
  p_captured_at timestamptz default now()
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller uuid := (select auth.uid());
  last_history_at timestamptz;
begin
  if caller is null then
    raise exception 'Authentication required';
  end if;
  if p_latitude not between -90 and 90 or p_longitude not between -180 and 180 then
    raise exception 'Invalid coordinates';
  end if;
  if not exists (
    select 1 from public.move_requests
    where id = p_move_id
      and driver_id = caller
      and status in ('driver_assigned', 'in_progress')
  ) then
    raise exception 'Driver is not assigned to this active move';
  end if;

  insert into public.driver_locations (
    move_id, driver_id, latitude, longitude, heading, speed, accuracy,
    captured_at, updated_at
  ) values (
    p_move_id, caller, p_latitude, p_longitude, p_heading, p_speed,
    p_accuracy, p_captured_at, now()
  )
  on conflict (move_id) do update set
    driver_id = excluded.driver_id,
    latitude = excluded.latitude,
    longitude = excluded.longitude,
    heading = excluded.heading,
    speed = excluded.speed,
    accuracy = excluded.accuracy,
    captured_at = excluded.captured_at,
    updated_at = now()
  where public.driver_locations.captured_at < excluded.captured_at;

  select max(captured_at) into last_history_at
  from public.tracking_points where move_id = p_move_id;

  if last_history_at is null or p_captured_at - last_history_at >= interval '1 minute' then
    insert into public.tracking_points (
      move_id, driver_id, latitude, longitude, heading, speed, accuracy,
      captured_at
    ) values (
      p_move_id, caller, p_latitude, p_longitude, p_heading, p_speed,
      p_accuracy, p_captured_at
    );
  end if;
end;
$$;

